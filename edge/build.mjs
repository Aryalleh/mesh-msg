// Builds the edge relay (docs/edge-relay.md) into one script per platform:
//
//   dist/cloudflare.js  ES module: export default { fetch, scheduled }
//   dist/arvan.js       service worker: addEventListener('fetch'), with a
//                       CONFIG placeholder the installer fills in
//
// The modules in src/ are joined into one scope (their import lines dropped,
// "export " removed), so names must be unique across src/. The admin panel
// and the trip map come from server/admin, as the Go relay serves them.
//
//   node edge/build.mjs           write dist/
//   node edge/build.mjs --check   fail if dist/ is out of date (CI)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
// Dependency order.
const modules = ['util.js', 'crypto.js', 'packet.js', 'store-d1.js', 'store-s3.js', 'relay.js', 'trips.js', 'admin.js', 'federate.js', 'api.js'];

function body(name) {
  const src = readFileSync(join(here, 'src', name), 'utf8');
  return `// ---- src/${name} ----\n` + src
    .replace(/^import [\s\S]*?from '[^']+';\n/gm, '')
    .replace(/^export (async function|function|const|let|class) /gm, '$1 ');
}

function assets() {
  const read = (p) => readFileSync(join(root, p), 'utf8');
  return [
    '// ---- assets (server/admin) ----',
    `const PANEL_HTML = ${JSON.stringify(read('server/admin/panel.html'))};`,
    `const TRIPMAP_HTML = ${JSON.stringify(read('server/admin/tripmap.html'))};`,
    `const TRIPCRYPTO_JS = ${JSON.stringify(read('server/admin/tripcrypto.js'))};`,
  ].join('\n');
}

const header = '// Mava edge relay (generated by edge/build.mjs from edge/src; do not edit).\n';
const core = [assets(), ...modules.map(body)].join('\n');

const out = {
  'cloudflare.js': header + core + '\n' + readFileSync(join(here, 'src', 'entry-cloudflare.js'), 'utf8').replace(/^import [\s\S]*?from '[^']+';\n/gm, ''),
  'arvan.js': header + core + '\n' + readFileSync(join(here, 'src', 'entry-arvan.js'), 'utf8').replace(/^import [\s\S]*?from '[^']+';\n/gm, ''),
};

const check = process.argv.includes('--check');
mkdirSync(join(here, 'dist'), { recursive: true });
let stale = false;
for (const [name, text] of Object.entries(out)) {
  const p = join(here, 'dist', name);
  let cur = '';
  try { cur = readFileSync(p, 'utf8'); } catch (e) { /* new */ }
  if (cur === text) continue;
  if (check) { console.error(`edge/dist/${name} is out of date: run node edge/build.mjs`); stale = true; } else { writeFileSync(p, text); console.log(`wrote edge/dist/${name} (${text.length} bytes)`); }
}
if (stale) process.exit(1);
